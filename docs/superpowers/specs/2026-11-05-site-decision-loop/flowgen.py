# Generates the two inline SVG flow diagrams (product / dev) used in diagram.html.
# Run from this folder: python flowgen.py -> flow_product.svg.html, flow_dev.svg.html,
# then paste each <svg> into the matching data-view section of diagram.html.
# v3 flow diagrams: product + dev, with failure / timeout / gate / tenant paths (after the Fable review).
import html
E = html.escape


class D:
    def __init__(s, w, h, pre):
        s.w, s.h, s.out, s.pre = w, h, [], pre
        s.cnt = {'have': 0, 'part': 0, 'miss': 0}

    def a(s, x):
        s.out.append(x)

    def band(s, x, y, w, h, title, cls=''):
        s.a(f'<rect class="band {cls}" x="{x}" y="{y}" width="{w}" height="{h}" rx="12"/>')
        s.a(f'<text class="band-t {cls}" x="{x+14}" y="{y+24}">{E(title)}</text>')

    def _text(s, cx, cy, t, cls=''):
        lines = t.split('\n')
        n = len(lines)
        for i, l in enumerate(lines):
            ty = cy + (i - (n - 1) / 2) * 14 + 4.5
            s.a(f'<text class="bt {cls}" x="{cx}" y="{ty:.1f}" text-anchor="middle">{E(l)}</text>')

    def box(s, x, y, w, h, t, st='have', cls=''):
        if st in s.cnt:
            s.cnt[st] += 1
        s.a(f'<rect class="bx {st} {cls}" x="{x}" y="{y}" width="{w}" height="{h}" rx="7"/>')
        s._text(x + w / 2, y + h / 2, t, cls)

    def dia(s, cx, cy, w, h, t, st='miss'):
        if st in s.cnt:
            s.cnt[st] += 1
        s.a(f'<polygon class="bx {st}" points="{cx},{cy-h/2} {cx+w/2},{cy} {cx},{cy+h/2} {cx-w/2},{cy}"/>')
        s._text(cx, cy, t)

    def cyl(s, x, y, w, t, st='have'):
        s.cnt[st] += 1
        h, r = 32, 6
        s.a(f'<path class="cy {st}" d="M{x},{y+r} v{h-2*r} a{w/2},{r} 0 0 0 {w},0 v-{h-2*r} a{w/2},{r} 0 0 0 -{w},0 a{w/2},{r} 0 0 0 {w},0"/>')
        s.a(f'<text class="bt sm" x="{x+w/2}" y="{y+h/2+8}" text-anchor="middle">{E(t)}</text>')

    def ln(s, pts, kind='main', label=None, lx=None, ly=None, anchor='start', arrow=True):
        d = 'M' + ' L'.join(f'{x},{y}' for x, y in pts)
        mk = f' marker-end="url(#{s.pre}-{kind})"' if arrow else ''
        s.a(f'<path class="ln {kind}" d="{d}"{mk}/>')
        if label:
            s.a(f'<text class="lt {kind}" x="{lx}" y="{ly}" text-anchor="{anchor}">{E(label)}</text>')

    def strip(s, x, y, w, t, cls=''):
        s.a(f'<rect class="strip {cls}" x="{x}" y="{y}" width="{w}" height="24" rx="6"/>')
        s.a(f'<text class="st {cls}" x="{x+10}" y="{y+16.5}">{E(t)}</text>')

    def note(s, x, y, t, cls='', anchor='start'):
        s.a(f'<text class="nt {cls}" x="{x}" y="{y}" text-anchor="{anchor}">{E(t)}</text>')

    def svg(s, label):
        defs = ''.join(
            f'<marker id="{s.pre}-{k}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path class="mk {k}" d="M0,0 L10,5 L0,10 z"/></marker>'
            for k in ('main', 'back', 'human', 'rec', 'stop'))
        return (f'<svg class="flow-svg" viewBox="0 0 {s.w} {s.h}" role="img" aria-label="{E(label)}"><defs>{defs}</defs>'
                + ''.join(s.out) + '</svg>')


